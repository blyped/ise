/** Substitution de jetons `{cle}`. Identique a `i18n/calls.ts` (web). */
export function tcNetworkCalls(template: string, values: Record<string, string | number>): string {
  return template.replace(/\{(\w+)\}/g, (match, key: string) =>
    key in values ? String(values[key]) : match,
  );
}
